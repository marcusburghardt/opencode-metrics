/**
 * Resolve the data directory for opencode-metrics.
 * Uses $XDG_DATA_HOME/opencode-metrics/ when set,
 * falling back to ~/.local/share/opencode-metrics/.
 */
export function getDataDir(): string {
	const xdgDataHome = process.env.XDG_DATA_HOME;
	const base =
		xdgDataHome && xdgDataHome.length > 0 ? xdgDataHome : path.join(homedir(), ".local", "share");
	return path.join(base, "opencode-metrics");
}

/**
 * Create the schema tables for the metrics database.
 * All statements use IF NOT EXISTS for idempotency.
 */
function createSchema(db: Database): void {
	db.run(`
		CREATE TABLE IF NOT EXISTS projects (
			project_id TEXT PRIMARY KEY,
			name       TEXT,
			worktree   TEXT
		)
	`);

	db.run(`
		CREATE TABLE IF NOT EXISTS sessions (
			session_id     TEXT PRIMARY KEY,
			project_id     TEXT,
			agent          TEXT,
			model          TEXT,
			classification TEXT,
			title          TEXT,
			started_at     INTEGER,
			ended_at       INTEGER,
			metadata       TEXT,
			budget_tag     TEXT,
			parent_session_id TEXT
		)
	`);

	db.run(`
		CREATE TABLE IF NOT EXISTS metric_definitions (
			metric_name TEXT PRIMARY KEY,
			unit        TEXT,
			description TEXT,
			aggregation TEXT
		)
	`);

	db.run(`
		CREATE TABLE IF NOT EXISTS measurements (
			session_id  TEXT,
			metric_name TEXT,
			value       REAL,
			recorded_at INTEGER,
			PRIMARY KEY (session_id, metric_name)
		)
	`);

	db.run(
		"CREATE INDEX IF NOT EXISTS idx_measurements_time ON measurements (recorded_at, metric_name)",
	);
	db.run(
		"CREATE INDEX IF NOT EXISTS idx_measurements_metric ON measurements (metric_name, recorded_at)",
	);

	// Convenience views exposing timestamps as epoch seconds and ISO-8601
	// strings. Base tables store epoch milliseconds (SDK passthrough);
	// these views eliminate the /1000 conversion gymnastics for Grafana
	// and other downstream consumers.
	db.run(V_SESSIONS_VIEW_SQL);

	db.run(`
		CREATE VIEW IF NOT EXISTS v_measurements AS
		SELECT
			session_id, metric_name, value,
			recorded_at / 1000 AS recorded_at_epoch,
			strftime('%Y-%m-%dT%H:%M:%SZ', recorded_at / 1000, 'unixepoch') AS recorded_at_iso
		FROM measurements
	`);

	// Session artifacts table — records specific PRs and issues a session
	// interacted with. PK deduplication ensures the same PR referenced
	// multiple times (view + diff + checks) produces one row, not three.
	db.run(`
		CREATE TABLE IF NOT EXISTS session_artifacts (
			session_id    TEXT,
			artifact_type TEXT,
			reference     TEXT,
			recorded_at   INTEGER,
			PRIMARY KEY (session_id, artifact_type, reference)
		)
	`);

	// Secondary index for cross-session artifact queries (e.g., "all
	// sessions that touched PR org/repo#123").
	db.run(
		"CREATE INDEX IF NOT EXISTS idx_artifacts_reference ON session_artifacts (reference, artifact_type)",
	);

	// Convenience view — same pattern as v_measurements: expose
	// recorded_at as epoch seconds and ISO-8601 string.
	db.run(`
		CREATE VIEW IF NOT EXISTS v_session_artifacts AS
		SELECT
			session_id, artifact_type, reference,
			recorded_at / 1000 AS recorded_at_epoch,
			strftime('%Y-%m-%dT%H:%M:%SZ', recorded_at / 1000, 'unixepoch') AS recorded_at_iso
		FROM session_artifacts
	`);

	// Task 1.1: measurement_deltas table — stores incremental changes per
	// metric on each idle event, enabling accurate time-sliced aggregation
	// (e.g., daily cost) even for multi-day sessions.
	db.run(`
		CREATE TABLE IF NOT EXISTS measurement_deltas (
			session_id  TEXT,
			metric_name TEXT,
			delta       REAL,
			recorded_at INTEGER,
			PRIMARY KEY (session_id, metric_name, recorded_at)
		)
	`);

	// Task 1.2: Secondary index for efficient cross-session aggregation
	// queries that filter by metric name and aggregate across time ranges.
	db.run(
		"CREATE INDEX IF NOT EXISTS idx_deltas_metric_time ON measurement_deltas (metric_name, recorded_at)",
	);

	// Task 1.3: Convenience view — same pattern as v_measurements:
	// expose recorded_at as epoch seconds and ISO-8601 string.
	db.run(`
		CREATE VIEW IF NOT EXISTS v_measurement_deltas AS
		SELECT
			session_id, metric_name, delta,
			recorded_at / 1000 AS recorded_at_epoch,
			strftime('%Y-%m-%dT%H:%M:%SZ', recorded_at / 1000, 'unixepoch') AS recorded_at_iso
		FROM measurement_deltas
	`);

	// Task 2.1: Cost pricing table — stores user-supplied per-token prices
	// for model patterns. Prices are in USD per million tokens. The
	// priority column reflects config array order (0 = highest priority)
	// for first-match-wins semantics in the adjusted cost views.
	db.run(`
		CREATE TABLE IF NOT EXISTS cost_pricing (
			model_pattern    TEXT PRIMARY KEY,
			priority         INTEGER NOT NULL,
			input_price      REAL NOT NULL,
			output_price     REAL NOT NULL,
			cache_read_price REAL,
			cache_write_price REAL,
			reasoning_price  REAL,
			description      TEXT,
			updated_at       INTEGER
		)
	`);

	// Task 2.2: Adjusted costs view — computes per-session adjusted cost
	// using user-supplied pricing rules matched via LIKE patterns.
	// Design decisions (see design.md D4, D5, D6):
	// - CTE-based pivoting: single pass over measurements EAV table
	// - First-match-wins: ROW_NUMBER() OVER (PARTITION BY ... ORDER BY priority)
	// - Reasoning price fallback: COALESCE(reasoning_price, output_price)
	// - No pricing match fallback: original cost passthrough via COALESCE
	db.run(`
		CREATE VIEW IF NOT EXISTS v_adjusted_costs AS
		WITH session_metrics AS (
			SELECT
				session_id,
				SUM(CASE WHEN metric_name = 'cost' THEN value END) AS cost,
				SUM(CASE WHEN metric_name = 'tokens_input' THEN value END) AS tokens_input,
				SUM(CASE WHEN metric_name = 'tokens_output' THEN value END) AS tokens_output,
				SUM(CASE WHEN metric_name = 'tokens_reasoning' THEN value END) AS tokens_reasoning,
				SUM(CASE WHEN metric_name = 'tokens_cache_read' THEN value END) AS tokens_cache_read,
				SUM(CASE WHEN metric_name = 'tokens_cache_write' THEN value END) AS tokens_cache_write,
				MAX(recorded_at) AS recorded_at
			FROM measurements
			GROUP BY session_id
		),
		matched_pricing AS (
			SELECT
				sm.session_id,
				cp.input_price,
				cp.output_price,
				cp.cache_read_price,
				cp.cache_write_price,
				cp.reasoning_price,
				ROW_NUMBER() OVER (
					PARTITION BY sm.session_id
					ORDER BY cp.priority
				) AS rn
			FROM session_metrics sm
			JOIN sessions s ON s.session_id = sm.session_id
			JOIN cost_pricing cp ON s.model LIKE cp.model_pattern
		)
		SELECT
			s.session_id,
			s.model,
			s.classification,
			s.budget_tag,
			s.project_id,
			sm.cost AS original_cost,
			COALESCE(
				(COALESCE(sm.tokens_input, 0) * mp.input_price / 1000000.0) +
				(COALESCE(sm.tokens_output, 0) * mp.output_price / 1000000.0) +
				(COALESCE(sm.tokens_cache_read, 0) * COALESCE(mp.cache_read_price, 0) / 1000000.0) +
				(COALESCE(sm.tokens_cache_write, 0) * COALESCE(mp.cache_write_price, 0) / 1000000.0) +
				(COALESCE(sm.tokens_reasoning, 0) * COALESCE(mp.reasoning_price, mp.output_price) / 1000000.0),
				sm.cost
			) AS adjusted_cost,
			COALESCE(
				(COALESCE(sm.tokens_input, 0) * mp.input_price / 1000000.0) +
				(COALESCE(sm.tokens_output, 0) * mp.output_price / 1000000.0) +
				(COALESCE(sm.tokens_cache_read, 0) * COALESCE(mp.cache_read_price, 0) / 1000000.0) +
				(COALESCE(sm.tokens_cache_write, 0) * COALESCE(mp.cache_write_price, 0) / 1000000.0) +
				(COALESCE(sm.tokens_reasoning, 0) * COALESCE(mp.reasoning_price, mp.output_price) / 1000000.0),
				sm.cost
			) - sm.cost AS cost_difference,
			sm.recorded_at / 1000 AS recorded_at_epoch,
			strftime('%Y-%m-%dT%H:%M:%SZ', sm.recorded_at / 1000, 'unixepoch') AS recorded_at_iso
		FROM session_metrics sm
		JOIN sessions s ON s.session_id = sm.session_id
		LEFT JOIN matched_pricing mp ON mp.session_id = sm.session_id AND mp.rn = 1
	`);

	// Task 2.3: Adjusted cost deltas view — same CTE pattern as
	// v_adjusted_costs but reading from measurement_deltas. Enables
	// accurate time-sliced adjusted cost aggregation for Grafana.
	db.run(`
		CREATE VIEW IF NOT EXISTS v_adjusted_cost_deltas AS
		WITH delta_metrics AS (
			SELECT
				session_id,
				SUM(CASE WHEN metric_name = 'cost' THEN delta END) AS cost_delta,
				SUM(CASE WHEN metric_name = 'tokens_input' THEN delta END) AS tokens_input,
				SUM(CASE WHEN metric_name = 'tokens_output' THEN delta END) AS tokens_output,
				SUM(CASE WHEN metric_name = 'tokens_reasoning' THEN delta END) AS tokens_reasoning,
				SUM(CASE WHEN metric_name = 'tokens_cache_read' THEN delta END) AS tokens_cache_read,
				SUM(CASE WHEN metric_name = 'tokens_cache_write' THEN delta END) AS tokens_cache_write,
				recorded_at
			FROM measurement_deltas
			GROUP BY session_id, recorded_at
		),
		matched_pricing AS (
			SELECT
				dm.session_id,
				dm.recorded_at,
				cp.input_price,
				cp.output_price,
				cp.cache_read_price,
				cp.cache_write_price,
				cp.reasoning_price,
				ROW_NUMBER() OVER (
					PARTITION BY dm.session_id, dm.recorded_at
					ORDER BY cp.priority
				) AS rn
			FROM delta_metrics dm
			JOIN sessions s ON s.session_id = dm.session_id
			JOIN cost_pricing cp ON s.model LIKE cp.model_pattern
		)
		SELECT
			s.session_id,
			s.model,
			s.classification,
			s.budget_tag,
			s.project_id,
			dm.cost_delta AS original_cost_delta,
			COALESCE(
				(COALESCE(dm.tokens_input, 0) * mp.input_price / 1000000.0) +
				(COALESCE(dm.tokens_output, 0) * mp.output_price / 1000000.0) +
				(COALESCE(dm.tokens_cache_read, 0) * COALESCE(mp.cache_read_price, 0) / 1000000.0) +
				(COALESCE(dm.tokens_cache_write, 0) * COALESCE(mp.cache_write_price, 0) / 1000000.0) +
				(COALESCE(dm.tokens_reasoning, 0) * COALESCE(mp.reasoning_price, mp.output_price) / 1000000.0),
				dm.cost_delta
			) AS adjusted_cost_delta,
			COALESCE(
				(COALESCE(dm.tokens_input, 0) * mp.input_price / 1000000.0) +
				(COALESCE(dm.tokens_output, 0) * mp.output_price / 1000000.0) +
				(COALESCE(dm.tokens_cache_read, 0) * COALESCE(mp.cache_read_price, 0) / 1000000.0) +
				(COALESCE(dm.tokens_cache_write, 0) * COALESCE(mp.cache_write_price, 0) / 1000000.0) +
				(COALESCE(dm.tokens_reasoning, 0) * COALESCE(mp.reasoning_price, mp.output_price) / 1000000.0),
				dm.cost_delta
			) - dm.cost_delta AS cost_delta_difference,
			dm.recorded_at / 1000 AS recorded_at_epoch,
			strftime('%Y-%m-%dT%H:%M:%SZ', dm.recorded_at / 1000, 'unixepoch') AS recorded_at_iso
		FROM delta_metrics dm
		JOIN sessions s ON s.session_id = dm.session_id
		LEFT JOIN matched_pricing mp ON mp.session_id = dm.session_id AND mp.recorded_at = dm.recorded_at AND mp.rn = 1
	`);

	// Sub-agent performance view — one row per agent/model/role combination.
	//
	// Both speed flavors are exposed deliberately:
	// - generation_seconds is time the model spent generating (true speed),
	//   available for live-captured sessions and backfilled sessions that
	//   carried `time.streamed` in their message history.
	// - duration_seconds is wall clock and includes permission prompts, tool
	//   execution, and idle time (effective throughput).
	//
	// Recreated on every init because `CREATE VIEW IF NOT EXISTS` would keep
	// a stale definition after a future schema change.
	db.run("DROP VIEW IF EXISTS v_agent_performance");
	db.run(`
		CREATE VIEW v_agent_performance AS
		WITH session_metrics AS (
			SELECT
				session_id,
				SUM(CASE WHEN metric_name = 'cost' THEN value END) AS cost,
				SUM(CASE WHEN metric_name = 'tokens_input' THEN value END) AS tokens_input,
				SUM(CASE WHEN metric_name = 'tokens_output' THEN value END) AS tokens_output,
				SUM(CASE WHEN metric_name = 'tokens_reasoning' THEN value END) AS tokens_reasoning,
				SUM(CASE WHEN metric_name = 'tokens_cache_read' THEN value END) AS tokens_cache_read,
				SUM(CASE WHEN metric_name = 'tokens_cache_write' THEN value END) AS tokens_cache_write,
				SUM(CASE WHEN metric_name = 'duration_seconds' THEN value END) AS duration_seconds,
				SUM(CASE WHEN metric_name = 'generation_seconds' THEN value END) AS generation_seconds,
				SUM(CASE WHEN metric_name = 'generation_output_tokens' THEN value END) AS generation_output_tokens,
				SUM(CASE WHEN metric_name = 'permission_wait_seconds' THEN value END) AS permission_wait_seconds,
				SUM(CASE WHEN metric_name = 'messages_total' THEN value END) AS messages_total,
				SUM(CASE WHEN metric_name = 'turns_total' THEN value END) AS turns_total,
				MAX(CASE WHEN metric_name = 'child_sessions' THEN value END) AS child_sessions
			FROM measurements
			GROUP BY session_id
		)
		SELECT
			s.agent,
			s.model,
			CASE WHEN s.parent_session_id IS NULL THEN 'root' ELSE 'subagent' END AS session_role,
			COUNT(*) AS runs,
			ROUND(SUM(sm.cost), 4) AS total_cost_usd,
			ROUND(AVG(sm.cost), 4) AS avg_cost_usd,
			ROUND(SUM(sm.tokens_input), 0) AS total_input_tokens,
			ROUND(SUM(sm.tokens_output), 0) AS total_output_tokens,
			ROUND(SUM(sm.tokens_cache_read), 0) AS total_cache_read_tokens,
			ROUND(SUM(sm.tokens_cache_write), 0) AS total_cache_write_tokens,
			ROUND(SUM(sm.duration_seconds), 0) AS total_wall_seconds,
			ROUND(AVG(sm.duration_seconds), 0) AS avg_wall_seconds,
			ROUND(SUM(sm.generation_seconds), 1) AS total_generation_seconds,
			ROUND(SUM(sm.generation_output_tokens), 0) AS total_generation_output_tokens,
			ROUND(AVG(sm.generation_seconds), 1) AS avg_generation_seconds,
			COUNT(CASE WHEN sm.generation_output_tokens IS NOT NULL THEN 1 END) AS runs_with_generation_time,
			ROUND(AVG(sm.permission_wait_seconds), 1) AS avg_permission_wait_seconds,
			ROUND(AVG(sm.messages_total), 1) AS avg_messages,
			ROUND(AVG(sm.turns_total), 1) AS avg_turns,
			ROUND(AVG(sm.child_sessions), 1) AS avg_child_sessions,
			ROUND(
				SUM(sm.tokens_output) / NULLIF(SUM(sm.duration_seconds), 0), 1
			) AS output_tokens_per_wall_second,
			ROUND(
				SUM(sm.generation_output_tokens)
				/ NULLIF(
					SUM(CASE WHEN sm.generation_output_tokens IS NOT NULL THEN sm.generation_seconds ELSE 0 END),
					0
				), 1
			) AS output_tokens_per_generation_second,
			ROUND(
				SUM(sm.cost) / NULLIF(SUM(sm.tokens_output), 0) * 1000, 4
			) AS usd_per_1k_output_tokens
		FROM sessions s
		JOIN session_metrics sm ON sm.session_id = s.session_id
		GROUP BY s.agent, s.model, session_role
	`);

	// Workflow cost rollup — attributes every session, at any depth, to its
	// root session. Root cost (the orchestrator's own model spend) and
	// sub-agent cost are reported separately so a workflow total is not
	// confused with a single session's cost.
	db.run("DROP VIEW IF EXISTS v_workflow_cost");
	db.run(`
		CREATE VIEW v_workflow_cost AS
		WITH RECURSIVE workflow(root_session_id, session_id, depth) AS (
			SELECT session_id, session_id, 0
			FROM sessions
			WHERE parent_session_id IS NULL
			   OR parent_session_id NOT IN (SELECT session_id FROM sessions)
			UNION ALL
			SELECT w.root_session_id, c.session_id, w.depth + 1
			FROM workflow w
			JOIN sessions c ON c.parent_session_id = w.session_id
		),
		per_session AS (
			SELECT
				session_id,
				SUM(CASE WHEN metric_name = 'cost' THEN value END) AS cost,
				SUM(CASE WHEN metric_name = 'tokens_output' THEN value END) AS tokens_output,
				SUM(CASE WHEN metric_name = 'duration_seconds' THEN value END) AS duration_seconds,
				SUM(CASE WHEN metric_name = 'generation_seconds' THEN value END) AS generation_seconds
			FROM measurements
			GROUP BY session_id
		),
		rollup AS (
			SELECT
				w.root_session_id,
				SUM(CASE WHEN w.depth = 0 THEN ps.cost ELSE 0 END) AS root_cost_usd,
				SUM(CASE WHEN w.depth > 0 THEN ps.cost ELSE 0 END) AS subagent_cost_usd,
				SUM(ps.cost) AS total_cost_usd,
				COUNT(*) - 1 AS subagent_sessions,
				SUM(CASE WHEN w.depth = 0 THEN ps.duration_seconds ELSE 0 END) AS root_wall_seconds,
				SUM(CASE WHEN w.depth > 0 THEN ps.duration_seconds ELSE 0 END) AS subagent_wall_seconds,
				SUM(ps.tokens_output) AS total_output_tokens,
				SUM(ps.generation_seconds) AS total_generation_seconds
			FROM workflow w
			LEFT JOIN per_session ps ON ps.session_id = w.session_id
			GROUP BY w.root_session_id
		)
		SELECT
			r.root_session_id,
			s.title AS root_title,
			s.agent AS root_agent,
			s.model AS root_model,
			s.classification,
			s.budget_tag,
			s.project_id,
			r.subagent_sessions,
			ROUND(r.root_cost_usd, 4) AS root_cost_usd,
			ROUND(r.subagent_cost_usd, 4) AS subagent_cost_usd,
			ROUND(r.total_cost_usd, 4) AS total_cost_usd,
			ROUND(r.subagent_cost_usd / NULLIF(r.total_cost_usd, 0), 4) AS subagent_cost_share,
			ROUND(r.root_wall_seconds, 0) AS root_wall_seconds,
			ROUND(r.subagent_wall_seconds, 0) AS subagent_wall_seconds,
			ROUND(r.total_output_tokens, 0) AS total_output_tokens,
			ROUND(r.total_generation_seconds, 1) AS total_generation_seconds
		FROM rollup r
		JOIN sessions s ON s.session_id = r.root_session_id
	`);
}

/**
 * Seed or refresh the metric_definitions table with the metric catalog.
 *
 * Uses an upsert on `metric_name` so descriptions stay current on an
 * existing database (for example, the V2 line-count limitation must be
 * visible to upgrading users). Names, units, and aggregation types are
 * unchanged by this update path.
 */
export function ensureMetricDefinitions(db: Database): void {
	const stmt = db.prepare(
		`INSERT INTO metric_definitions (metric_name, unit, description, aggregation)
		 VALUES (?, ?, ?, ?)
		 ON CONFLICT(metric_name) DO UPDATE SET description = excluded.description`,
	);

	for (const metric of METRIC_DEFINITIONS) {
		stmt.run(metric.metric_name, metric.unit, metric.description, metric.aggregation);
	}
}

/**
 * Count the stored sessions whose parent is the given session.
 *
 * Only direct children are counted; grandchildren belong to their own
 * parent. A malformed row that points a session at itself is excluded so
 * the count never reports the session as its own child.
 */
export function countChildSessions(db: Database, sessionID: string): number {
	const row = db
		.prepare(
			"SELECT COUNT(*) AS count FROM sessions WHERE parent_session_id = ? AND session_id != ?",
		)
		.get(sessionID, sessionID) as { count: number } | null;
	return row?.count ?? 0;
}

/**
 * Result returned by initDatabase(), giving the caller both the
 * opened Database handle and the resolved data directory path.
 */
export interface InitDatabaseResult {
	db: Database;
	dataDir: string;
}

/**
 * Initialize the metrics database.
 *
 * 1. Resolves the data directory (XDG_DATA_HOME or fallback).
 * 2. Creates the directory with 0o755 if it doesn't exist.
 * 3. Opens (or creates) metrics.db with WAL mode and busy_timeout.
 * 4. Creates all schema tables idempotently.
 * 5. Sets PRAGMA user_version on first creation.
 * 6. Seeds the metric_definitions catalog.
 *
 * @param dataDirOverride — optional path override for testing.
 */
export function initDatabase(dataDirOverride?: string): InitDatabaseResult {
	const dataDir = dataDirOverride ?? getDataDir();

	if (!existsSync(dataDir)) {
		mkdirSync(dataDir, { recursive: true, mode: 0o755 });
	}

	const dbPath = path.join(dataDir, "metrics.db");
	const isNewDb = !existsSync(dbPath);
	const db = new Database(dbPath, { create: true });

	// Ensure restrictive permissions on the database file (0o644).
	if (isNewDb) {
		chmodSync(dbPath, 0o644);
	}

	// WAL mode for concurrent read access and busy_timeout for contention.
	db.run("PRAGMA journal_mode = WAL");
	db.run("PRAGMA busy_timeout = 5000");

	createSchema(db);

	// Schema versioning: set user_version when the database schema is
	// behind the current version. CREATE TABLE/INDEX/VIEW IF NOT EXISTS
	// makes the migration idempotent — the version bump reflects the
	// actual schema state after createSchema() runs.
	const versionRow = db.prepare("PRAGMA user_version").get() as { user_version: number } | null;
	const currentVersion = versionRow?.user_version ?? 0;

	// V2 → V3 migration: add budget_tag column to sessions table.
	// Guard with try/catch because ALTER TABLE ADD COLUMN fails if the
	// column already exists (e.g., fresh v3 database created by
	// createSchema above). SQLite does not support IF NOT EXISTS for
	// ALTER TABLE ADD COLUMN.
	if (currentVersion < 3) {
		try {
			db.run("ALTER TABLE sessions ADD COLUMN budget_tag TEXT");
		} catch (_error: unknown) {
			// Column already exists — safe to ignore (fresh v3 database
			// or migration already applied).
		}
	}

	// V3 → V4 migration: add cost_pricing table and adjusted cost views.
	// No ALTER TABLE needed — the new table and views are created by
	// createSchema() above with IF NOT EXISTS. The version bump below
	// reflects the actual schema state after createSchema() runs.
	// (Guard is implicit: currentVersion < 4 falls through to the
	// generic version bump below.)

	// V4 → V5 migration: fix projects with empty or sentinel names.
	// Non-git projects were recorded with name = '' (from path.basename("/"))
	// and worktree = "/". Set name to "unknown" so the upsert guard can
	// later overwrite it when better data arrives.
	if (currentVersion < 5) {
		db.run("UPDATE projects SET name = 'unknown' WHERE name = '' OR name IS NULL");
	}

	// V5 → V6 migration: add parent_session_id column to sessions table.
	// Guard with try/catch for the same reason as the V2 → V3 migration:
	// SQLite has no `ALTER TABLE ... ADD COLUMN IF NOT EXISTS`, and a fresh
	// v6 database already has the column from createSchema(). Existing rows
	// end up NULL, which is the correct value for a root/sub-agent-unknown
	// session.
	if (currentVersion < 6) {
		try {
			db.run("ALTER TABLE sessions ADD COLUMN parent_session_id TEXT");
		} catch (_error: unknown) {
			// Column already exists — safe to ignore.
		}

		// `CREATE VIEW IF NOT EXISTS` does not alter an existing view, so an
		// upgrading v5 database would keep the old v_sessions definition
		// without parent_session_id. Drop and recreate it once.
		db.run("DROP VIEW IF EXISTS v_sessions");
		db.run(V_SESSIONS_VIEW_SQL);
	}

	// Secondary index for sub-agent tree queries (subagent-linking spec).
	// Created after the migration so it can rely on the column existing on
	// both fresh and upgraded databases.
	db.run("CREATE INDEX IF NOT EXISTS idx_sessions_parent ON sessions (parent_session_id)");

	if (currentVersion < SCHEMA_VERSION) {
		db.run(`PRAGMA user_version = ${SCHEMA_VERSION}`);
	}

	ensureMetricDefinitions(db);

	return { db, dataDir };
}
